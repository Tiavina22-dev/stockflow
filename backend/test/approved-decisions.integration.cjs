require('reflect-metadata'); require('dotenv/config');
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { PrismaClient } = require('@prisma/client');
const { OperationsService } = require('../dist/operations');
const { InvoicesService } = require('../dist/invoices');
const { ShopAccess } = require('../dist/auth');
const { invoiceTotals, formatAmount } = require('../dist/money');
test('choix approuvés : TTC, facture immuable, révision, consommation interne et inventaire zéro', async () => {
 const url = new URL(process.env.DATABASE_URL); url.pathname='/stockflow_test';
 const db = new PrismaClient({datasources:{db:{url:url.toString()}}});
 try {
 const code=randomUUID();
 const role=await db.role.create({data:{code,name:code}});
 const user=await db.user.create({data:{name:code,login:code,passwordHash:'unusable',roleId:role.id}});
 const shop=await db.shop.create({data:{code,name:code}});
 const category=await db.category.create({data:{name:code}});
 const unit=await db.unit.create({data:{name:code}});
 const product=await db.product.create({data:{name:'Original',reference:code,categoryId:category.id,unitId:unit.id,supplierPrice:'2',salePrice:'105'}});
 const actor={id:user.id,permissions:['shops.all','stock.in','stock.out','stock.inventory','stock.adjust','sales.create','sales.validate','sales.correct','invoices.create'],shopIds:[]};
 const ops=new OperationsService(db,new ShopAccess()); const invoices=new InvoicesService(db,new ShopAccess(),ops);
 await db.stockSettings.upsert({where:{id:'global'},create:{allowNegativeStock:true},update:{allowNegativeStock:true}});
 await db.companySettings.upsert({where:{id:'global'},create:{taxRate:5},update:{taxRate:5}});
 const body=(type,quantity,extra={})=>({type,shopId:shop.id,businessDate:'2026-10-01',status:'VALIDATED',requestKey:randomUUID(),lines:[{productId:product.id,quantity:String(quantity),unitPrice:'105'}],...extra});
 await ops.create(body('STOCK_IN',10),actor);
 const sale=await ops.create(body('SALE',1),actor);
 const invoice=await invoices.issue({saleOperationId:sale.id},actor);
 assert.equal(invoice.snapshot.totalHt,'100.00'); assert.equal(invoice.snapshot.taxAmount,'5.00'); assert.equal(invoice.snapshot.hideTaxOnPrint,true);
 assert.equal((await invoices.issue({saleOperationId:sale.id},actor)).id,invoice.id);
 await db.companySettings.update({where:{id:'global'},data:{name:'Changed',taxRate:20}});
 await db.product.update({where:{id:product.id},data:{name:'Changed'}});
 assert.equal((await invoices.get(invoice.id,actor)).snapshot.lines[0].name,'Original');
 await assert.rejects(db.customerInvoice.update({where:{id:invoice.id},data:{reason:'overwrite'}}));
 const revision=await ops.create(body('SALE',2,{reason:'Correction'}),actor,sale.id);
 assert.equal(revision.taxRate.toString(),'5');
 await assert.rejects(invoices.issue({saleOperationId:revision.id},actor));
 const replacement=await invoices.issue({saleOperationId:revision.id,reason:'Correction'},actor);
 assert.equal(replacement.originalInvoiceId,invoice.id);
 await assert.rejects(ops.create(body('STOCK_OUT',1,{stockOutPurpose:'INTERNAL_CONSUMPTION'}),actor));
 const consumption=await ops.create(body('STOCK_OUT',9,{stockOutPurpose:'INTERNAL_CONSUMPTION',reason:'Usage interne'}),actor);
 assert.equal(consumption.total.toString(),'0'); assert.ok(consumption.warnings.length);
 await ops.create(body('INVENTORY_ADJUSTMENT',0,{reason:'Comptage physique'}),actor);
 const before=await db.stockMovement.count({where:{productId:product.id}});
 await ops.create(body('INVENTORY_ADJUSTMENT',0,{reason:'Comptage physique'}),actor);
 assert.equal(await db.stockMovement.count({where:{productId:product.id}}),before);
 assert.equal(invoiceTotals('120','20').taxAmount,'20.00');
 assert.match(formatAmount('10','Ar'),/10,00/);
 } finally {await db.$disconnect();}
});
