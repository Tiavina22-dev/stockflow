// Tests sur une base dédiée, jamais sur la base de travail.
require('reflect-metadata'); require('dotenv/config');
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { PrismaClient } = require('@prisma/client');
const { OperationsService } = require('../dist/operations');
const { ShopAccess } = require('../dist/auth');
const url = new URL(process.env.DATABASE_URL);
url.pathname = '/stockflow_test';
const db = new PrismaClient({ datasources: { db: { url: url.toString() } } });
test('transactions réelles : stock, transferts, ventes, révisions, concurrence et reprise', { timeout: 120000 }, async () => {
  const prefix = randomUUID();
  const role = await db.role.create({ data: { code: prefix, name: 'Test' } });
  const user = await db.user.create({ data: { name: 'Test', login: prefix, passwordHash: 'non-utilisable', roleId: role.id } });
  const actor = { id: user.id, name: 'Test', login: prefix, role: 'ADMIN', permissions: ['shops.all', 'stock.in', 'stock.out', 'stock.return', 'stock.transfer', 'stock.inventory','stock.adjust', 'sales.create', 'sales.validate', 'sales.cancel', 'sales.correct'], shopIds: [] };
  const a = await db.shop.create({ data: { code: `${prefix}-a`, name: 'A' } });
  const b = await db.shop.create({ data: { code: `${prefix}-b`, name: 'B' } });
  const cat = await db.category.create({ data: { name: prefix } });
  const unit = await db.unit.create({ data: { name: prefix } });
  const product = await db.product.create({ data: { name: 'Test', reference: prefix, categoryId: cat.id, unitId: unit.id, supplierPrice: '8', salePrice: '10' } });
  const service = new OperationsService(db, new ShopAccess());
  const body = (type, quantity, extra = {}) => ({ type, shopId: a.id, businessDate: '2026-09-30', status: 'VALIDATED', requestKey: randomUUID(), lines: [{ productId: product.id, quantity: String(quantity), unitPrice: '10' }], ...extra });
  const balance = async shopId => (await db.stockBalance.findUniqueOrThrow({ where: { productId_shopId: { productId: product.id, shopId } } })).quantity.toString();
  try {
    const entryBody = body('STOCK_IN', '10');
    const entry = await service.create(entryBody, actor);
    assert.equal(await balance(a.id), '10');
    assert.equal((await service.create(entryBody, actor)).id, entry.id);
    assert.equal(await balance(a.id), '10');
    await assert.rejects(service.create({ ...entryBody, lines: [{ productId: product.id, quantity: '11' }] }, actor));
    const sale = await service.create(body('SALE', '3'), actor);
    assert.equal(await balance(a.id), '7');
    assert.equal(sale.total.toString(), '30');
    assert.equal(sale.lines[0].supplierPrice.toString(), '8');
    await service.create(body('TRANSFER', '2', { destinationShopId: b.id }), actor);
    assert.equal(await balance(a.id), '5'); assert.equal(await balance(b.id), '2');
    await service.create(body('CUSTOMER_RETURN', '1'), actor);
    assert.equal(await balance(a.id), '6');
    await db.product.update({ where: { id: product.id }, data: { supplierPrice: '9' } });
    const correction = await service.create(body('SALE', '2', { reason: 'Quantité corrigée' }), actor, sale.id);
    assert.equal(await balance(a.id), '7');
    assert.equal(correction.lines[0].supplierPrice.toString(), '8');
    const original = await db.operation.findUniqueOrThrow({ where: { id: sale.id }, include: { lines: true } });
    assert.equal(original.superseded, true); assert.equal(original.lines[0].quantity.toString(), '3');
    await service.cancel(correction.id, actor, 'Annulation test'); assert.equal(await balance(a.id), '9');
    await service.create(body('INVENTORY_ADJUSTMENT', '1.5', {reason:'Comptage physique'}), actor); assert.equal(await balance(a.id), '1.5');
    await db.stockSettings.upsert({ where: { id: 'global' }, create: { allowNegativeStock: false }, update: { allowNegativeStock: false } });
    const count = await db.operation.count();
    await assert.rejects(service.create(body('STOCK_OUT', '2'), actor));
    assert.equal(await balance(a.id), '1.5'); assert.equal(await db.operation.count(), count);
    const results = await Promise.allSettled([service.create(body('SALE', '1'), actor), service.create(body('SALE', '1'), actor)]);
    assert.equal(results.filter(r => r.status === 'fulfilled').length, 1); assert.equal(await balance(a.id), '0.5');
    const draft = await service.create(body('STOCK_IN', '4', { status: 'DRAFT' }), actor);
    assert.equal(await balance(a.id), '0.5'); await service.validate(draft.id, actor); assert.equal(await balance(a.id), '4.5');
    await assert.rejects(service.validate(draft.id, actor));
    const sum = await db.stockMovement.aggregate({ where: { productId: product.id, shopId: a.id }, _sum: { quantityDelta: true } });
    assert.equal(sum._sum.quantityDelta.toString(), await balance(a.id));
    const outsider = { ...actor, permissions: ['stock.in'], shopIds: [b.id] };
    await assert.rejects(service.create(body('STOCK_IN', '5'), outsider));
  } finally { await db.$disconnect(); }
});
