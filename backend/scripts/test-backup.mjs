import 'dotenv/config';
import pg from 'pg';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdir, writeFile, readFile, cp } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createBackup, verifyArchive, postgresEnvironment, postgresTool } from './backup-tools.mjs';
const url=new URL(process.env.DATABASE_URL);
if(url.hostname!=='127.0.0.1'||url.port!=='55432') throw Error('Base locale dédiée requise');
url.pathname='/stockflow_test';
const root=resolve('.local/backup-tests',randomUUID()); const uploads=join(root,'source');
await mkdir(uploads,{recursive:true}); await writeFile(join(uploads,'justificatif.txt'),'Original conservé');
try { await cp(resolve(process.env.UPLOAD_DIR ?? '.local/uploads'),uploads,{recursive:true}); } catch(e) { if(e.code!=='ENOENT')throw e; }
const archive=await createBackup({root:join(root,'archives'),databaseUrl:url.toString(),uploadDirectory:uploads});
await verifyArchive(archive.directory);
assert.equal(await readFile(join(archive.directory,'uploads/justificatif.txt'),'utf8'),'Original conservé');
const admin=new pg.Client({connectionString:url.toString()}); await admin.connect();
const name='stockflow_restore_'+randomUUID().replaceAll('-','');
await admin.query(`CREATE DATABASE "${name}"`);
const original=await admin.query('SELECT count(*)::int AS n FROM "CustomerInvoice"');
const finance=await admin.query('SELECT count(*)::int AS n FROM "FinanceOperation"');
const attachments=await admin.query('SELECT location FROM "FinanceAttachment"');await admin.end();
url.pathname='/'+name;
await promisify(execFile)(await postgresTool('pg_restore'),['--no-owner','--no-acl','--no-password','--dbname',name,join(archive.directory,'database.dump')],{windowsHide:true,env:postgresEnvironment(url.toString())});
const restored=new pg.Client({connectionString:url.toString()}); await restored.connect();
assert.equal((await restored.query('SELECT count(*)::int AS n FROM "CustomerInvoice"')).rows[0].n,original.rows[0].n);
assert.equal((await restored.query('SELECT count(*)::int AS n FROM "FinanceOperation"')).rows[0].n,finance.rows[0].n);
for(const attachment of attachments.rows) assert.ok((await readFile(join(archive.directory,'uploads',attachment.location))).length);
await restored.end();
await writeFile(join(archive.directory,'uploads/justificatif.txt'),'corrupted');
await assert.rejects(verifyArchive(archive.directory));
console.log('Sauvegarde, restauration PostgreSQL, justificatifs et détection de corruption : OK');
